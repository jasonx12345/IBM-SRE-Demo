"""Render rule constants from config/slo.yaml so objectives cannot silently drift."""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def build_rules(slo: dict) -> dict:
    rules = []
    windows = sorted(
        {
            window
            for alert in slo["burn_alerts"].values()
            for window in (alert["long_window"], alert["short_window"])
        }
    )
    for window in windows:
        requests = (
            f'sum(rate(toil_budget_http_requests_total{{job="toil-budget",scope="api"}}[{window}]))'
        )
        errors = f'(sum(rate(toil_budget_http_requests_total{{job="toil-budget",scope="api",status=~"5.."}}[{window}])) or vector(0))'
        durations = f'sum(rate(toil_budget_http_request_duration_seconds_count{{job="toil-budget",scope="api"}}[{window}]))'
        good = f'sum(rate(toil_budget_http_request_duration_seconds_bucket{{job="toil-budget",scope="api",le="{slo["latency"]["threshold_seconds"]:g}"}}[{window}]))'
        rules.extend(
            [
                {
                    "record": f"toil_budget:api_error_ratio:{window}",
                    "expr": f"{errors} / clamp_min({requests}, 1e-9)",
                },
                {
                    "record": f"toil_budget:api_slow_ratio:{window}",
                    "expr": f"clamp_min({durations} - {good}, 0) / clamp_min({durations}, 1e-9)",
                },
            ]
        )
    alerts = []
    for name, spec in slo["burn_alerts"].items():
        for signal, objective, title in (
            ("error", slo["availability"]["objective"], "Availability"),
            ("slow", slo["latency"]["objective"], "Latency"),
        ):
            limit = spec["burn_rate"] * (1 - objective)
            alerts.append(
                {
                    "alert": f"ToilBudget{title}{name.title()}Burn",
                    "expr": f"(toil_budget:api_{signal}_ratio:{spec['long_window']} > {limit:g}) and (toil_budget:api_{signal}_ratio:{spec['short_window']} > {limit:g})",
                    "for": spec["for"],
                    "labels": {
                        "severity": spec["severity"],
                        "service": "toil-budget",
                        "slo": signal,
                    },
                    "annotations": {
                        "summary": f"Toil Budget API {title.lower()} SLO burning at >{spec['burn_rate']}x",
                        "description": f"Both {spec['long_window']} and {spec['short_window']} exceed the burn threshold. Check app logs, DB readiness, CPU/memory and request latency. See docs/OPERATIONS.md.",
                    },
                }
            )
    alerts.append(
        {
            "alert": "ToilBudgetUnavailable",
            "expr": 'up{job="toil-budget"} == 0 or toil_budget_database_up{job="toil-budget"} == 0',
            "for": "2m",
            "labels": {"severity": "critical", "service": "toil-budget"},
            "annotations": {
                "summary": "Toil Budget app or database is unavailable",
                "description": "Inspect /readyz, PostgreSQL health and app logs. See docs/OPERATIONS.md.",
            },
        }
    )
    return {
        "groups": [
            {"name": "toil-budget-slo-recording", "rules": rules},
            {"name": "toil-budget-slo-alerts", "rules": alerts},
        ]
    }


if __name__ == "__main__":
    slo = yaml.safe_load((ROOT / "config/slo.yaml").read_text(encoding="utf-8"))
    (ROOT / "prometheus/rules.yaml").write_text(
        "# Generated by python -m prometheus.generate_rules; edit config/slo.yaml.\n"
        + yaml.safe_dump(build_rules(slo), sort_keys=False),
        encoding="utf-8",
    )
