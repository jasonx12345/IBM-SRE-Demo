"""Embed the canonical YAML in a ConfigMap; no Kustomize parent-path exceptions."""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def build_configmap():
    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {"name": "toil-budget-config", "namespace": "toil-budget"},
        "data": {
            name: (ROOT / "config" / name).read_text(encoding="utf-8")
            for name in ("thresholds.yaml", "model.yaml", "slo.yaml")
        },
    }


if __name__ == "__main__":
    (ROOT / "k8s/configmap.yaml").write_text(
        "# Generated by python -m k8s.generate_config.\n"
        + yaml.safe_dump(build_configmap(), sort_keys=False),
        encoding="utf-8",
    )
